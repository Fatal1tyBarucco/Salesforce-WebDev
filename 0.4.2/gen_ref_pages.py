"""Generate code-derived reference pages at build time (mkdocs-gen-files).

ADR-012: the manual nav is kept minimal; repetitive reference surfaces are
derived from the REAL ``src/`` tree on every build.  This script produces the
virtual page ``reference/code-tree.md`` (whitelisted in the sync engine and
contract validator as GENERATED_PAGES — it has no tracked file).

The tracked, deterministic counterpart is ``docs/reference/repo-index.md``
(regenerated by ``docs_sync_engine.py reconcile`` and committed by the bot).
"""

from __future__ import annotations

from pathlib import Path

import mkdocs_gen_files

SRC = Path("src")
DOCS = Path("docs")


def _tree(root: Path, prefix: str = "") -> list[str]:
    lines: list[str] = []
    entries = sorted(
        (p for p in root.iterdir() if p.name != "__pycache__"),
        key=lambda p: (p.is_file(), p.name),
    )
    for i, entry in enumerate(entries):
        last = i == len(entries) - 1
        branch = "└── " if last else "├── "
        if entry.is_dir():
            lines.append(f"{prefix}{branch}{entry.name}/")
            lines.extend(_tree(entry, prefix + ("    " if last else "│   ")))
        elif entry.suffix == ".py":
            lines.append(f"{prefix}{branch}{entry.name}")
    return lines


def _evoker(module: Path) -> str:
    inner = module.relative_to(SRC).with_suffix("").parts
    return "api/" + "-".join(inner) + ".md"


def main() -> None:
    lines = [
        "# Árvore de Código",
        "",
        "Página gerada em tempo de build por `docs/gen_ref_pages.py`",
        "(mkdocs-gen-files) a partir da árvore real de `src/` (ADR-012).",
        "",
        "## Estrutura de `src/`",
        "",
        "```text",
        "src/",
        *_tree(SRC),
        "```",
        "",
        "## Módulos e referências de API",
        "",
        "| Módulo | Referência |",
        "| :--- | :--- |",
    ]
    for module in sorted(SRC.rglob("*.py")):
        if module.name == "__init__.py":
            continue
        dotted = "src." + ".".join(module.relative_to(SRC).with_suffix("").parts)
        evoker = _evoker(module)
        if (DOCS / evoker).is_file():
            lines.append(f"| `{dotted}` | [API](../{evoker}) |")
        else:
            lines.append(f"| `{dotted}` | — |")
    lines.append("")
    with mkdocs_gen_files.open("reference/code-tree.md", "w") as fd:
        fd.write("\n".join(lines))
    mkdocs_gen_files.set_edit_path("reference/code-tree.md", "docs/gen_ref_pages.py")


main()
